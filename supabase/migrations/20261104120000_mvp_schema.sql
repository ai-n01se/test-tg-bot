begin;

-- 1. Перейменування
alter table "STUDENT_TEACHER_RELATIONS" rename column balanc to balance;
alter table "SLOTS" rename column student_id to relation_id;
alter table "SLOTS" rename constraint "SLOTS_student_id_fkey" to "SLOTS_relation_id_fkey";

-- 2. Типи й значення за замовчуванням
alter table "STUDENT_TEACHER_RELATIONS"
  alter column balance type numeric(10,2) using balance::numeric(10,2),
  alter column balance set default 0;

alter table "SLOTS"
  alter column appointment_time type timestamptz using appointment_time::timestamptz;

-- 3. Унікальність
alter table "STUDENT_TEACHER_RELATIONS"
  add constraint student_teacher_unique unique (users_id, teacher_id);

alter table "SLOTS"
  add constraint slots_teacher_time_unique unique (teacher_id, appointment_time);

-- 4. Нові поля вчителя
alter table "TEACHER_PROFILES"
  add column price_per_lesson numeric(10,2) not null default 0,
  add column subjects text,
  add column bio text,
  add column is_public boolean not null default true;

-- 5. Нові поля слота
alter table "SLOTS"
  add column duration_minutes integer not null default 60,
  add column reminder_sent boolean not null default false;

-- 6. Нові типи
create type payment_status as enum ('pending', 'confirmed', 'rejected');
create type balance_transaction_type as enum ('topup', 'lesson_charge', 'refund', 'manual');

-- 7. Таблиця оплат
create table "PAYMENTS" (
  id bigint generated by default as identity primary key,
  relation_id bigint not null references "STUDENT_TEACHER_RELATIONS"(id) on delete cascade,
  amount numeric(10,2) not null check (amount > 0),
  screenshot_file_id text,
  status payment_status not null default 'pending',
  created_at timestamptz not null default now(),
  confirmed_at timestamptz
);

-- 8. Журнал змін балансу
create table "BALANCE_TRANSACTIONS" (
  id bigint generated by default as identity primary key,
  relation_id bigint not null references "STUDENT_TEACHER_RELATIONS"(id) on delete cascade,
  amount numeric(10,2) not null,
  type balance_transaction_type not null,
  slot_id bigint references "SLOTS"(id) on delete set null,
  payment_id bigint references "PAYMENTS"(id) on delete set null,
  created_at timestamptz not null default now()
);

-- 9. Захист: бот працює через service role, який обходить RLS,
--    а публічний ключ без політик не отримає доступу до даних
alter table "PROFILES" enable row level security;
alter table "TEACHER_PROFILES" enable row level security;
alter table "STUDENT_TEACHER_RELATIONS" enable row level security;
alter table "SLOTS" enable row level security;
alter table "ADMIN_PROFILES" enable row level security;
alter table "PAYMENTS" enable row level security;
alter table "BALANCE_TRANSACTIONS" enable row level security;

commit;
